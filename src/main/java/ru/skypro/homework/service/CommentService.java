package ru.skypro.homework.service;

import ru.skypro.homework.dto.CommentDTO;
import ru.skypro.homework.dto.CommentsList;

/**
 * Сервис для управления комментариями к объявлениям.
 * <p>
 * Определяет контракт для работы с комментариями: создание, чтение, обновление и удаление.
 * Реализует бизнес-логику, связанную с комментариями, включая проверку прав доступа
 * и обеспечение целостности данных (комментарий должен принадлежать объявлению).
 * </p>
 *
 * <p><b>Безопасность и права доступа:</b></p>
 * <ul>
 *   <li><b>Чтение:</b> публичный доступ ко всем комментариям объявления</li>
 *   <li><b>Создание:</b> любой аутентифицированный пользователь</li>
 *   <li><b>Обновление/удаление:</b> только автор комментария или администратор</li>
 *   <li><b>Проверка принадлежности:</b> комментарий должен принадлежать указанному объявлению</li>
 * </ul>
 *
 * <p><b>Архитектурная роль:</b></p>
 * <ul>
 *   <li><b>Слой сервисов:</b> инкапсулирует бизнес-логику комментариев</li>
 *   <li><b>Абстракция:</b> отделяет контроллер от репозиториев и мапперов</li>
 *   <li><b>Транзакционность:</b> операции с комментариями выполняются в транзакциях</li>
 *   <li><b>Консистентность:</b> обеспечивает целостность связей между сущностями</li>
 * </ul>
 *
 * @see ru.skypro.homework.service.impl.CommentServiceImpl
 * @see ru.skypro.homework.controller.CommentController
 * @see ru.skypro.homework.model.Comments
 */
public interface CommentService {

    /**
     * Получает все комментарии для указанного объявления (публичный доступ).
     * <p>
     * Возвращает список всех комментариев, связанных с объявлением.
     * Комментарии сортируются по дате создания (от новых к старым).
     * </p>
     *
     * <p><b>Используется в эндпоинте:</b> {@code GET /ads/{id}/comments}</p>
     *
     * <p><b>Процесс получения:</b></p>
     * <ol>
     *   <li>Проверка существования объявления</li>
     *   <li>Получение всех комментариев через репозиторий</li>
     *   <li>Сортировка по {@code createdAt} (DESC)</li>
     *   <li>Преобразование сущностей в DTO</li>
     *   <li>Возврат структурированного списка с пагинацией</li>
     * </ol>
     *
     * <p><b>Возвращаемые данные:</b></p>
     * <pre>
     * {
     *   "count": 25,
     *   "results": [
     *     {
     *       "pk": 456,
     *       "author": 123,
     *       "authorImage": "/uploads/avatars/user123.jpg",
     *       "authorFirstName": "John",
     *       "createdAt": 1736935200000,
     *       "text": "Отличное предложение!"
     *     },
     *     ...
     *   ]
     * }
     * </pre>
     *
     * @param id идентификатор объявления
     * @return список комментариев с пагинацией
     * @throws org.webjars.NotFoundException если объявление не найдено
     * @see ru.skypro.homework.controller.CommentController#(Long)
     * @see ru.skypro.homework.dto.CommentsList
     */
    CommentsList getCommentsByAds(Long id);

    /**
     * Создает новый комментарий к объявлению от текущего пользователя.
     * <p>
     * Автор комментария определяется автоматически из контекста безопасности.
     * Комментарий связывается с указанным объявлением.
     * </p>
     *
     * <p><b>Используется в эндпоинте:</b> {@code POST /ads/{id}/comments}</p>
     *
     * <p><b>Процесс создания:</b></p>
     * <ol>
     *   <li>Валидация текста комментария (не null, не пустой, длина ≤ 1000)</li>
     *   <li>Поиск объявления по ID</li>
     *   <li>Определение текущего пользователя как автора</li>
     *   <li>Создание сущности {@link ru.skypro.homework.model.Comments}</li>
     *   <li>Установка текущего времени как {@code createdAt}</li>
     *   <li>Сохранение комментария в базу данных</li>
     *   <li>Возврат созданного комментария в формате DTO</li>
     * </ol>
     *
     * <p><b>Требования к комментарию:</b></p>
     * <ul>
     *   <li><b>Текст:</b> 1-1000 символов, не пустой</li>
     *   <li><b>Объявление:</b> должно существовать</li>
     *   <li><b>Пользователь:</b> должен быть аутентифицирован</li>
     *   <li><b>Частота:</b> возможны ограничения на частоту комментирования</li>
     * </ul>
     *
     * @param adId идентификатор объявления, к которому добавляется комментарий
     * @param text текст комментария
     * @return DTO созданного комментария
     * @throws org.webjars.NotFoundException                             если объявление не найдено
     * @throws IllegalArgumentException                                  если текст комментария невалиден
     * @throws org.springframework.security.access.AccessDeniedException если пользователь не аутентифицирован
     * @see ru.skypro.homework.controller.CommentController#(Long)
     * @see ru.skypro.homework.model.Comments
     */
    CommentDTO createComment(Long adId, String text);

    /**
     * Удаляет комментарий.
     * <p>
     * Удаляет комментарий только если текущий пользователь является его автором
     * или имеет роль администратора. Проверяет, что комментарий принадлежит
     * указанному объявлению.
     * </p>
     *
     * <p><b>Используется в эндпоинте:</b> {@code DELETE /ads/{adId}/comments/{commentId}}</p>
     *
     * <p><b>Процесс удаления:</b></p>
     * <ol>
     *   <li>Поиск комментария по ID</li>
     *   <li>Проверка, что комментарий принадлежит указанному объявлению</li>
     *   <li>Проверка прав доступа (автор или администратор)</li>
     *   <li>Удаление комментария из базы данных</li>
     *   <li>Каскадное удаление связанных данных (если настроено)</li>
     * </ol>
     *
     * <p><b>Сценарии ошибок:</b></p>
     * <table border="1">
     *   <tr><th>Сценарий</th><th>Исключение</th><th>HTTP Status</th></tr>
     *   <tr><td>Комментарий не найден</td><td>NotFoundException</td><td>404 Not Found</td></tr>
     *   <tr><td>Не принадлежит объявлению</td><td>IllegalArgumentException</td><td>400 Bad Request</td></tr>
     *   <tr><td>Нет прав на удаление</td><td>AccessDeniedException</td><td>403 Forbidden</td></tr>
     * </table>
     *
     * @param adId      идентификатор объявления (для проверки принадлежности)
     * @param commentId идентификатор комментария для удаления
     * @throws org.webjars.NotFoundException                             если комментарий или объявление не найдены
     * @throws IllegalArgumentException                                  если комментарий не принадлежит указанному объявлению
     * @throws org.springframework.security.access.AccessDeniedException если нет прав на удаление
     * @see ru.skypro.homework.controller.CommentController#(Long, Long)
     */
    void deleteComment(Long adId, Long commentId);

    /**
     * Обновляет текст существующего комментария.
     * <p>
     * Обновляет текст комментария только если текущий пользователь является его автором
     * или имеет роль администратора. Проверяет принадлежность комментария к объявлению.
     * </p>
     *
     * <p><b>Используется в эндпоинте:</b> {@code PATCH /ads/{adId}/comments/{commentId}}</p>
     *
     * <p><b>Процесс обновления:</b></p>
     * <ol>
     *   <li>Поиск комментария по ID</li>
     *   <li>Проверка принадлежности к указанному объявлению</li>
     *   <li>Проверка прав доступа (автор или администратор)</li>
     *   <li>Валидация нового текста</li>
     *   <li>Обновление поля {@code text} в сущности</li>
     *   <li>Обновление поля {@code updatedAt} (если есть)</li>
     *   <li>Сохранение изменений в БД</li>
     *   <li>Возврат обновленного комментария в формате DTO</li>
     * </ol>
     *
     * <p><b>Ограничения редактирования (рекомендуется добавить):</b></p>
     * <ul>
     *   <li>Можно редактировать только в течение 30 минут после создания</li>
     *   <li>Ограниченное количество правок (например, не более 3 раз)</li>
     *   <li>Запрет на редактирование после получения ответов</li>
     * </ul>
     *
     * @param adId      идентификатор объявления (для проверки принадлежности)
     * @param commentId идентификатор комментария для обновления
     * @param text      новый текст комментария
     * @return DTO обновленного комментария
     * @throws org.webjars.NotFoundException                             если комментарий или объявление не найдены
     * @throws IllegalArgumentException                                  если комментарий не принадлежит объявлению или текст невалиден
     * @throws org.springframework.security.access.AccessDeniedException если нет прав на обновление
     * @see ru.skypro.homework.controller.CommentController#(Long, Long)
     */
    CommentDTO updateComment(Long adId, Long commentId, String text);
}
