package ru.skypro.homework.model;

import lombok.*;

import javax.persistence.*;
import java.util.List;

/**
 * Сущность "Объявление" (Ad/Advertisement) - основная бизнес-сущность системы.
 * <p>
 * Представляет товар или услугу, предлагаемую пользователем на платформе.
 * Содержит информацию о товаре, цену, изображение и связи с автором и комментариями.
 * </p>
 *
 * <p><b>Таблица в базе данных:</b> {@code ads}</p>
 *
 * <p><b>Связи с другими сущностями:</b></p>
 * <ul>
 *   <li>N:1 с {@link Users} - каждое объявление имеет одного автора</li>
 *   <li>1:N с {@link Comments} - каждое объявление может иметь множество комментариев</li>
 * </ul>
 *
 * <p><b>Бизнес-правила:</b></p>
 * <ul>
 *   <li>Объявление всегда должно иметь автора</li>
 *   <li>Цена не может быть отрицательной</li>
 *   <li>При удалении автора все его объявления удаляются (каскад)</li>
 *   <li>При удалении объявления все комментарии к нему удаляются (каскад)</li>
 * </ul>
 *
 * @see Users
 * @see Comments
 */
@Entity  // Объявляет класс как JPA сущность
@Data  // Lombok: генерирует геттеры, сеттеры, toString, equals, hashCode
@AllArgsConstructor  // Lombok: генерирует конструктор со всеми полями
@NoArgsConstructor  // Lombok: генерирует конструктор без аргументов (требуется JPA)
@Getter
@Setter
@Table(name = "ads")
public class Ads {

    /**
     * Уникальный идентификатор объявления.
     * <p>
     * Используется в API как {@code pk} (primary key).
     * Автоматически генерируется базой данных с автоинкрементом.
     * Это поле является первичным ключом таблицы.
     * </p>
     *
     * <p><b>В API отображается как:</b> {@code pk}</p>
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long pk;

    /**
     * Путь к основному изображению объявления.
     * <p>
     * Содержит относительный путь к файлу изображения.
     * Формат: {@code /uploads/ads/{filename}.jpg}
     * Может быть null, если изображение не загружено.
     * </p>
     *
     * <p><b>В API отображается как:</b> {@code image}</p>
     *
     * <p><b>Рекомендации:</b></p>
     * <ul>
     *   <li>Оптимальный размер: 800x600 пикселей</li>
     *   <li>Поддерживаемые форматы: JPEG, PNG</li>
     *   <li>Максимальный размер: 10MB</li>
     * </ul>
     */
    @Column(name = "image_url")
    private String image;

    /**
     * Подробное описание товара или услуги.
     * <p>
     * Содержит детальную информацию о предлагаемом товаре/услуге:
     * состояние, характеристики, дополнительные условия и т.д.
     * </p>
     *
     * <p><b>В API отображается как:</b> {@code description}</p>
     *
     * <p><b>Ограничения:</b></p>
     * <ul>
     *   <li>Не может быть null</li>
     *   <li>Максимальная длина: 64 символа (очень мало! Рекомендуется увеличить)</li>
     * </ul>
     *
     * <p><b>Рекомендация:</b> Увеличить длину до 1000+ символов для полноценных описаний.</p>
     */
    @Column(nullable = false, length = 64)
    private String description;

    /**
     * Цена товара или услуги в рублях.
     * <p>
     * Целочисленное значение (копейки не поддерживаются).
     * Для поддержки дробных значений рекомендуется использовать {@link java.math.BigDecimal}.
     * </p>
     *
     * <p><b>В API отображается как:</b> {@code price}</p>
     *
     * <p><b>Ограничения:</b></p>
     * <ul>
     *   <li>Не может быть null</li>
     *   <li>Должна быть положительной или нулевой (для "договорной" цены)</li>
     * </ul>
     *
     * <p><b>Рекомендация:</b> Добавить валидацию {@code @Min(0)}.</p>
     */
    @Column(nullable = false)
    private Integer price;

    /**
     * Заголовок объявления.
     * <p>
     * Краткое название товара или услуги.
     * Отображается в списках объявлений и на карточках.
     * </p>
     *
     * <p><b>В API отображается как:</b> {@code title}</p>
     *
     * <p><b>Ограничения:</b></p>
     * <ul>
     *   <li>Не может быть null</li>
     *   <li>Максимальная длина: 32 символа (мало! Рекомендуется 100+)</li>
     * </ul>
     *
     * <p><b>Рекомендации по содержанию:</b></p>
     * <ul>
     *   <li>Кратко и информативно</li>
     *   <li>Включает ключевые характеристики</li>
     *   <li>Привлекает внимание</li>
     * </ul>
     */
    @Column(nullable = false, length = 32)
    private String title;

    /**
     * Автор (создатель) объявления.
     * <p>
     * Связь "многие-к-одному" с сущностью {@link Users}.
     * Каждое объявление принадлежит одному пользователю.
     * Загружается лениво (LAZY) для оптимизации производительности.
     * </p>
     *
     * <p><b>Внешний ключ:</b> {@code author_id} в таблице ads</p>
     *
     * <p><b>Каскадные операции:</b></p>
     * <ul>
     *   <li>По умолчанию нет каскада (объявление не удаляется при удалении автора)</li>
     *   <li>Лучше добавить {@code @ManyToOne(cascade = CascadeType.REMOVE)} или настроить каскад через Users</li>
     * </ul>
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "author_id", nullable = false)
    @ToString.Exclude
    private Users author;

    /**
     * Список комментариев к объявлению.
     * <p>
     * Связь "один-ко-многим" с сущностью {@link Comments}.
     * Каждое объявление может иметь множество комментариев.
     * Загружается лениво (LAZY) для оптимизации производительности.
     * </p>
     *
     * <p><b>Каскадные операции:</b></p>
     * <ul>
     *   <li>ALL - все операции каскадируются на комментарии</li>
     *   <li>При удалении объявления удаляются все его комментарии</li>
     *   <li>При сохранении объявления сохраняются связанные комментарии</li>
     * </ul>
     */
    @OneToMany(mappedBy = "ad", cascade = CascadeType.ALL, fetch = FetchType.LAZY)
    @ToString.Exclude
    private List<Comments> comments;
}
